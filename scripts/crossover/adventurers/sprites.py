"""Hand-authored, private-preview-only low-poly crossover adventurers.

Each function returns one SVG group. No rendering or writes occur on import.
Coordinates are feet-grounded: y=0, upper-left lighting. IDs use crossover-.
Local conservative bounds including shadows and gear:
  gon: (-27, -122, 110, 8), body (-26, -122, 34, 0)
  killua: (-27, -123, 28, 8), body (-27, -123, 28, 0)
  link: (-39, -121, 37, 8), body/gear (-38, -121, 37, 0)
Gon's fishing line and rod are separately addressable, permitting gentle motion.
"""


class _Drawing:
    """A per-call builder; no shared mutable state."""
    def __init__(self, name, label, x, y, s):
        self.parts = [f'<g id="crossover-{name}" aria-label="{label}" transform="translate({x:g} {y:g}) scale({s:g})">']

    def poly(self, points, fill, **attrs):
        a = ' '.join(f'{k.replace("_", "-")}="{v}"' for k, v in attrs.items())
        d = 'M' + 'L'.join(f'{x:g} {y:g}' for x, y in points) + 'Z'
        self.parts.append(f'<path d="{d}" fill="{fill}" {a}/>')

    def path(self, d, fill='none', **attrs):
        a = ' '.join(f'{k.replace("_", "-")}="{v}"' for k, v in attrs.items())
        self.parts.append(f'<path d="{d}" fill="{fill}" {a}/>')

    def ellipse(self, x, y, rx, ry, fill, opacity=1, **attrs):
        a = ' '.join(f'{k.replace("_", "-")}="{v}"' for k, v in attrs.items())
        self.parts.append(f'<ellipse cx="{x:g}" cy="{y:g}" rx="{rx:g}" ry="{ry:g}" fill="{fill}" opacity="{opacity}" {a}/>')

    def add(self, markup):
        self.parts.append(markup)

    def finish(self):
        return '\n'.join(self.parts) + '\n</g>'


