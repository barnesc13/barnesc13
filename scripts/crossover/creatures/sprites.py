"""Handmade private-preview SVG creatures. All functions are pure; no file/network I/O.
Local origin (x,y) is the ground contact. Light comes from upper left.
The returned groups use crossover- IDs and contain no embedded raster content.
"""
from html import escape

class _Sprite:
    def __init__(self, name, label, x, y, s):
        self.parts = [f'<g id="crossover-{name}" aria-label="{escape(label)}" transform="translate({x:g} {y:g}) scale({s:g})">']
    def poly(self, pts, color):
        self.parts.append('<path d="M'+'L'.join(f'{x:g} {y:g}' for x,y in pts)+f'Z" fill="{color}"/>')
    def path(self, d, color='none', **attrs):
        a=' '.join(f'{k.replace("_","-")}="{v}"' for k,v in attrs.items())
        self.parts.append(f'<path d="{d}" fill="{color}" {a}/>')
    def ellipse(self,x,y,rx,ry,color,opacity=1):
        self.parts.append(f'<ellipse cx="{x}" cy="{y}" rx="{rx}" ry="{ry}" fill="{color}" opacity="{opacity}"/>')
    def finish(self):
        return ''.join(self.parts)+'</g>'


